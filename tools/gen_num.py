#!/usr/bin/env python3
"""Generates crates/kiln_resolve/std/num.kn: the methods and constants of the
integer types, which are the same for each type apart from its name, width,
and signedness. Run from the repository root after editing:

    python3 tools/gen_num.py
"""

INTS = [
    ("i8", 8, True), ("i16", 16, True), ("i32", 32, True), ("i64", 64, True), ("isize", 64, True),
    ("u8", 8, False), ("u16", 16, False), ("u32", 32, False), ("u64", 64, False), ("usize", 64, False),
]

def unsigned_of(t):
    return "u" + t[1:] if t.startswith("i") else t

def limits(bits, signed):
    if signed:
        hi = 2 ** (bits - 1) - 1
        # The most negative value has no positive literal of the same type.
        return f"-{hi} - 1", str(hi)
    return "0", str(2 ** bits - 1)

def gen(t, bits, signed):
    u = unsigned_of(t)
    lo, hi = limits(bits, signed)
    out = [f"impl {t} {{"]
    a = out.append
    a(f"\t// The smallest value{': -2^' + str(bits - 1) if signed else ''}.")
    a(f"\tpub const MIN: {t} = {lo}")
    a(f"\t// The largest value.")
    a(f"\tpub const MAX: {t} = {hi}")
    a(f"\t// The size in bits.")
    a(f"\tpub const BITS: u32 = {bits}")
    a("")
    a("\t// Arithmetic that wraps around at the ends of the range instead of")
    a("\t// panicking on overflow.")
    for op in ["add", "sub", "mul"]:
        a(f"\tpub fn wrapping_{op}(self, b: {t}) -> {t}")
    a(f"\tpub fn wrapping_neg(self) -> {t}")
    a("\t// Shifts by `n % BITS`.")
    a(f"\tpub fn wrapping_shl(self, n: u32) -> {t}")
    a(f"\tpub fn wrapping_shr(self, n: u32) -> {t}")
    a("")
    a("\t// The wrapped result and whether it overflowed.")
    for op in ["add", "sub", "mul"]:
        a(f"\tpub fn overflowing_{op}(self, b: {t}) -> ({t}, bool)")
    a("")
    a("\t// Bit operations.")
    a("\tpub fn count_ones(self) -> u32")
    a("\tpub fn leading_zeros(self) -> u32")
    a("\tpub fn trailing_zeros(self) -> u32")
    a(f"\tpub fn rotate_left(self, n: u32) -> {t}")
    a(f"\tpub fn rotate_right(self, n: u32) -> {t}")
    a(f"\tpub fn swap_bytes(self) -> {t}")
    a(f"\tpub fn reverse_bits(self) -> {t}")
    a("")
    a("\tpub fn count_zeros(self) -> u32 {")
    a(f"\t\treturn {bits} - self.count_ones()")
    a("\t}")
    a("")
    # checked
    for op in ["add", "sub", "mul"]:
        a(f"\t// `None` on overflow.")
        a(f"\tpub fn checked_{op}(self, b: {t}) -> Option<{t}> {{")
        a(f"\t\t(r, o) := self.overflowing_{op}(b)")
        a("\t\tif o {")
        a("\t\t\treturn None")
        a("\t\t}")
        a("\t\treturn Some(r)")
        a("\t}")
        a("")
    overflow_div = f" || (self == {t}::MIN && b == -1)" if signed else ""
    for op, sym in [("div", "/"), ("rem", "%")]:
        a(f"\t// `None` if `b` is zero{' or the result overflows' if signed else ''}.")
        a(f"\tpub fn checked_{op}(self, b: {t}) -> Option<{t}> {{")
        a(f"\t\tif b == 0{overflow_div} {{")
        a("\t\t\treturn None")
        a("\t\t}")
        a(f"\t\treturn Some(self {sym} b)")
        a("\t}")
        a("")
    a(f"\tpub fn checked_neg(self) -> Option<{t}> {{")
    if signed:
        a(f"\t\tif self == {t}::MIN {{")
        a("\t\t\treturn None")
        a("\t\t}")
        a("\t\treturn Some(-self)")
    else:
        a("\t\tif self != 0 {")
        a("\t\t\treturn None")
        a("\t\t}")
        a("\t\treturn Some(0)")
    a("\t}")
    a("")
    # saturating
    a("\t// Arithmetic that stops at MIN or MAX instead of overflowing.")
    a(f"\tpub fn saturating_add(self, b: {t}) -> {t} {{")
    a("\t\t(r, o) := self.overflowing_add(b)")
    a("\t\tif !o {")
    a("\t\t\treturn r")
    a("\t\t}")
    if signed:
        a("\t\tif b < 0 {")
        a(f"\t\t\treturn {t}::MIN")
        a("\t\t}")
    a(f"\t\treturn {t}::MAX")
    a("\t}")
    a("")
    a(f"\tpub fn saturating_sub(self, b: {t}) -> {t} {{")
    a("\t\t(r, o) := self.overflowing_sub(b)")
    a("\t\tif !o {")
    a("\t\t\treturn r")
    a("\t\t}")
    if signed:
        a("\t\tif b < 0 {")
        a(f"\t\t\treturn {t}::MAX")
        a("\t\t}")
    a(f"\t\treturn {t}::MIN")
    a("\t}")
    a("")
    a(f"\tpub fn saturating_mul(self, b: {t}) -> {t} {{")
    a("\t\t(r, o) := self.overflowing_mul(b)")
    a("\t\tif !o {")
    a("\t\t\treturn r")
    a("\t\t}")
    if signed:
        a("\t\tif (self < 0) != (b < 0) {")
        a(f"\t\t\treturn {t}::MIN")
        a("\t\t}")
    a(f"\t\treturn {t}::MAX")
    a("\t}")
    a("")
    # pow
    a("\t// `self` to the power `exp`. Panics on overflow (see `checked_pow`).")
    a(f"\tpub fn pow(self, exp: u32) -> {t} {{")
    a("\t\tmatch self.checked_pow(exp) {")
    a("\t\t\tSome(r) => return r,")
    a('\t\t\tNone => panic("attempt to raise to a power with overflow"),')
    a("\t\t}")
    a("\t}")
    a("")
    a(f"\tpub fn checked_pow(self, exp: u32) -> Option<{t}> {{")
    a(f"\t\tlet mut r: {t} = 1")
    a("\t\tbase mut := self")
    a("\t\te mut := exp")
    a("\t\twhile e > 0 {")
    a("\t\t\tif e & 1 == 1 {")
    a("\t\t\t\tr = r.checked_mul(base)?")
    a("\t\t\t}")
    a("\t\t\te >>= 1")
    a("\t\t\tif e > 0 {")
    a("\t\t\t\tbase = base.checked_mul(base)?")
    a("\t\t\t}")
    a("\t\t}")
    a("\t\treturn Some(r)")
    a("\t}")
    a("")
    a(f"\tpub fn wrapping_pow(self, exp: u32) -> {t} {{")
    a(f"\t\tlet mut r: {t} = 1")
    a("\t\tbase mut := self")
    a("\t\te mut := exp")
    a("\t\twhile e > 0 {")
    a("\t\t\tif e & 1 == 1 {")
    a("\t\t\t\tr = r.wrapping_mul(base)")
    a("\t\t\t}")
    a("\t\t\te >>= 1")
    a("\t\t\tbase = base.wrapping_mul(base)")
    a("\t\t}")
    a("\t\treturn r")
    a("\t}")
    a("")
    a(f"\tpub fn saturating_pow(self, exp: u32) -> {t} {{")
    a("\t\tmatch self.checked_pow(exp) {")
    a("\t\t\tSome(r) => return r,")
    a("\t\t\tNone => {")
    if signed:
        a("\t\t\t\tif self < 0 && exp % 2 == 1 {")
        a(f"\t\t\t\t\treturn {t}::MIN")
        a("\t\t\t\t}")
    a(f"\t\t\t\treturn {t}::MAX")
    a("\t\t\t}")
    a("\t\t}")
    a("\t}")
    a("")
    # min / max / clamp
    a(f"\tpub fn min(self, b: {t}) -> {t} {{")
    a("\t\tif b < self {")
    a("\t\t\treturn b")
    a("\t\t}")
    a("\t\treturn self")
    a("\t}")
    a("")
    a(f"\tpub fn max(self, b: {t}) -> {t} {{")
    a("\t\tif b > self {")
    a("\t\t\treturn b")
    a("\t\t}")
    a("\t\treturn self")
    a("\t}")
    a("")
    a("\t// `self` limited to `lo..=hi`.")
    a(f"\tpub fn clamp(self, lo: {t}, hi: {t}) -> {t} {{")
    a("\t\tif self < lo {")
    a("\t\t\treturn lo")
    a("\t\t}")
    a("\t\tif self > hi {")
    a("\t\t\treturn hi")
    a("\t\t}")
    a("\t\treturn self")
    a("\t}")
    a("")
    a("\t// The distance between `self` and `b`, which never overflows.")
    a(f"\tpub fn abs_diff(self, b: {t}) -> {u} {{")
    a("\t\tif self < b {")
    a(f"\t\t\treturn (b as {u}).wrapping_sub(self as {u})")
    a("\t\t}")
    a(f"\t\treturn (self as {u}).wrapping_sub(b as {u})")
    a("\t}")
    a("")
    if signed:
        a("\t// The absolute value. Panics for MIN in debug builds.")
        a(f"\tpub fn abs(self) -> {t} {{")
        a("\t\tif self < 0 {")
        a("\t\t\treturn -self")
        a("\t\t}")
        a("\t\treturn self")
        a("\t}")
        a("")
        a("\t// The absolute value as an unsigned number (never overflows).")
        a(f"\tpub fn unsigned_abs(self) -> {u} {{")
        a("\t\tif self < 0 {")
        a(f"\t\t\treturn (0 as {u}).wrapping_sub(self as {u})")
        a("\t\t}")
        a(f"\t\treturn self as {u}")
        a("\t}")
        a("")
        a("\t// -1, 0, or 1.")
        a(f"\tpub fn signum(self) -> {t} {{")
        a("\t\tif self < 0 {")
        a("\t\t\treturn -1")
        a("\t\t}")
        a("\t\tif self > 0 {")
        a("\t\t\treturn 1")
        a("\t\t}")
        a("\t\treturn 0")
        a("\t}")
        a("")
        a("\tpub fn is_negative(self) -> bool {")
        a("\t\treturn self < 0")
        a("\t}")
        a("")
        a("\tpub fn is_positive(self) -> bool {")
        a("\t\treturn self > 0")
        a("\t}")
        a("")
        a("\t// Euclidean division: the quotient for which the remainder is never")
        a("\t// negative (`-7.div_euclid(2)` is -4).")
        a(f"\tpub fn div_euclid(self, b: {t}) -> {t} {{")
        a("\t\tq := self / b")
        a("\t\tif self % b < 0 {")
        a("\t\t\tif b > 0 {")
        a("\t\t\t\treturn q - 1")
        a("\t\t\t}")
        a("\t\t\treturn q + 1")
        a("\t\t}")
        a("\t\treturn q")
        a("\t}")
        a("")
        a("\t// The remainder of Euclidean division, in `0..b.abs()`.")
        a(f"\tpub fn rem_euclid(self, b: {t}) -> {t} {{")
        a("\t\tr := self % b")
        a("\t\tif r < 0 {")
        a("\t\t\treturn r + b.abs()")
        a("\t\t}")
        a("\t\treturn r")
        a("\t}")
        a("")
    else:
        a(f"\tpub fn div_euclid(self, b: {t}) -> {t} {{")
        a("\t\treturn self / b")
        a("\t}")
        a("")
        a(f"\tpub fn rem_euclid(self, b: {t}) -> {t} {{")
        a("\t\treturn self % b")
        a("\t}")
        a("")
        a("\t// Whether the value is a power of two (0 is not).")
        a("\tpub fn is_power_of_two(self) -> bool {")
        a("\t\treturn self != 0 && self & (self - 1) == 0")
        a("\t}")
        a("")
        a("\t// The smallest power of two that is at least `self`. Panics on")
        a("\t// overflow in debug builds.")
        a(f"\tpub fn next_power_of_two(self) -> {t} {{")
        a("\t\tif self <= 1 {")
        a("\t\t\treturn 1")
        a("\t\t}")
        a(f"\t\tshift := {bits} - (self - 1).leading_zeros()")
        a(f"\t\tif shift >= {bits} {{")
        a('\t\t\tpanic("next_power_of_two overflowed")')
        a("\t\t}")
        a(f"\t\treturn (1 as {t}) << shift")
        a("\t}")
        a("")
    a("\t// The base-2 logarithm, rounded down. Panics if `self <= 0`.")
    a("\tpub fn ilog2(self) -> u32 {")
    a("\t\tif self <= 0 {")
    a('\t\t\tpanic("ilog2 of a non-positive number")')
    a("\t\t}")
    a(f"\t\treturn {bits - 1} - self.leading_zeros()")
    a("\t}")
    a("")
    a("\t// The base-10 logarithm, rounded down. Panics if `self <= 0`.")
    a("\tpub fn ilog10(self) -> u32 {")
    a("\t\tif self <= 0 {")
    a('\t\t\tpanic("ilog10 of a non-positive number")')
    a("\t\t}")
    a("\t\tn mut := 0")
    a("\t\tv mut := self")
    a("\t\twhile v >= 10 {")
    a("\t\t\tv /= 10")
    a("\t\t\tn += 1")
    a("\t\t}")
    a("\t\treturn n")
    a("\t}")
    a("")
    a("\t// The integer square root, rounded down. Panics if negative.")
    a(f"\tpub fn isqrt(self) -> {t} {{")
    a("\t\tif self < 0 {")
    a('\t\t\tpanic("isqrt of a negative number")')
    a("\t\t}")
    a("\t\tif self < 2 {")
    a("\t\t\treturn self")
    a("\t\t}")
    a("\t\t// Newton's method from an overestimate.")
    a(f"\t\tx mut := (1 as {t}) << ((self.ilog2() / 2) + 1)")
    a("\t\twhile true {")
    a("\t\t\ty := (x + self / x) / 2")
    a("\t\t\tif y >= x {")
    a("\t\t\t\treturn x")
    a("\t\t\t}")
    a("\t\t\tx = y")
    a("\t\t}")
    a("\t\treturn x")
    a("\t}")
    a("")
    a("\t// The decimal text of the number.")
    a("\tpub fn to_string(self) -> String {")
    a('\t\treturn "{self}"')
    a("\t}")
    a("")
    a("\t// Parses decimal text, like `strconv::parse_int`.")
    a(f"\tpub fn parse(s: &str) -> Result<{t}, std::strconv::ParseError> {{")
    a(f"\t\treturn {t}::from_str_radix(s, 10)")
    a("\t}")
    a("")
    a("\t// Parses text in base `radix` (2 to 36), with an optional sign")
    a("\t// (and `_` separators between digits).")
    a(f"\tpub fn from_str_radix(s: &str, radix: u32) -> Result<{t}, std::strconv::ParseError> {{")
    a(f"\t\tv := std::strconv::parse_digits(s, radix, {'true' if signed else 'false'}, {bits})?")
    a(f"\t\treturn Ok(v as {t})")
    a("\t}")
    out.append("}")
    return "\n".join(out)

def main():
    parts = [
        "// GENERATED by tools/gen_num.py; do not edit by hand.",
        "//",
        "// Methods and constants of the integer types: overflow-aware arithmetic",
        "// (`checked_*`, `wrapping_*`, `saturating_*`, `overflowing_*`), `pow`,",
        "// `abs`, Euclidean division, logarithms, bit operations, and parsing.",
        "//",
        "//\tu8::MAX                     // 255",
        "//\tx.checked_add(y)            // None on overflow",
        "//\ti64::parse(\"-42\")?         // -42",
        "",
    ]
    for t, bits, signed in INTS:
        parts.append(gen(t, bits, signed))
        parts.append("")
    open("crates/kiln_resolve/std/num.kn", "w").write("\n".join(parts).rstrip() + "\n")

if __name__ == "__main__":
    main()
