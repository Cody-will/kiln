#!/usr/bin/env python3
"""Generates crates/kiln_runtime/runtime/kiln_unicode.c: Unicode character
classes and simple case mappings for std::unicode, from Python's unicodedata.

    python3 tools/gen_unicode.py
"""
import os
import unicodedata

def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

cat = lambda c: unicodedata.category(chr(c))
# White_Space property (PropList.txt); unicodedata has no direct accessor.
SPACE = {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680, 0x2028, 0x2029,
         0x202F, 0x205F, 0x3000} | set(range(0x2000, 0x200B))
classes = [
    ("letter", lambda c: cat(c)[0] == "L" or cat(c) == "Nl"),
    ("digit", lambda c: cat(c) == "Nd"),
    ("number", lambda c: cat(c)[0] == "N"),
    ("upper", lambda c: cat(c) in ("Lu", "Lt")),
    ("lower", lambda c: cat(c) == "Ll"),
    ("punct", lambda c: cat(c)[0] == "P"),
    ("symbol", lambda c: cat(c)[0] == "S"),
    ("mark", lambda c: cat(c)[0] == "M"),
    ("control", lambda c: cat(c) == "Cc"),
    ("space", lambda c: c in SPACE),
]

def case_map(f):
    out = []
    for c in range(0x110000):
        s = chr(c)
        if 0xD800 <= c <= 0xDFFF:
            continue
        m = f(s)
        if len(m) == 1 and m != s:
            out.append((c, ord(m)))
    return out

lines = [
    "/* Generated by tools/gen_unicode.py from Unicode %s. Do not edit. */" % unicodedata.unidata_version,
    "",
    "#include <stdint.h>",
    "",
    "typedef struct { uint32_t lo, hi; } kn_range;",
    "typedef struct { uint32_t from, to; } kn_pair;",
    "",
]
for name, pred in classes:
    rs = ranges(pred)
    lines.append("static const kn_range %s_tab[%d] = {" % (name, len(rs)))
    for i in range(0, len(rs), 4):
        lines.append("\t" + " ".join("{0x%X, 0x%X}," % r for r in rs[i:i + 4]))
    lines.append("};")
    lines.append("")
for name, f in (("upper", str.upper), ("lower", str.lower)):
    ps = case_map(f)
    lines.append("static const kn_pair to_%s_tab[%d] = {" % (name, len(ps)))
    for i in range(0, len(ps), 4):
        lines.append("\t" + " ".join("{0x%X, 0x%X}," % p for p in ps[i:i + 4]))
    lines.append("};")
    lines.append("")
lines += [
    "static int in_ranges(const kn_range *t, int n, uint32_t c) {",
    "\tint lo = 0, hi = n - 1;",
    "\twhile (lo <= hi) {",
    "\t\tint mid = (lo + hi) / 2;",
    "\t\tif (c < t[mid].lo)",
    "\t\t\thi = mid - 1;",
    "\t\telse if (c > t[mid].hi)",
    "\t\t\tlo = mid + 1;",
    "\t\telse",
    "\t\t\treturn 1;",
    "\t}",
    "\treturn 0;",
    "}",
    "",
    "static uint32_t map_pair(const kn_pair *t, int n, uint32_t c) {",
    "\tint lo = 0, hi = n - 1;",
    "\twhile (lo <= hi) {",
    "\t\tint mid = (lo + hi) / 2;",
    "\t\tif (c < t[mid].from)",
    "\t\t\thi = mid - 1;",
    "\t\telse if (c > t[mid].from)",
    "\t\t\tlo = mid + 1;",
    "\t\telse",
    "\t\t\treturn t[mid].to;",
    "\t}",
    "\treturn c;",
    "}",
    "",
    "#define N(t) ((int)(sizeof(t) / sizeof((t)[0])))",
    "",
    "/* Whether c is in class k (the order of `classes` in gen_unicode.py). */",
    "int64_t kn_unicode_is(int64_t c, int64_t k) {",
    "\tuint32_t u = (uint32_t)c;",
    "\tswitch (k) {",
]
for i, (name, _) in enumerate(classes):
    lines.append("\tcase %d: return in_ranges(%s_tab, N(%s_tab), u);" % (i, name, name))
lines += [
    "\tdefault: return 0;",
    "\t}",
    "}",
    "",
    "/* The simple uppercase (upper != 0) or lowercase mapping of c. */",
    "int64_t kn_unicode_to(int64_t c, int64_t upper) {",
    "\tuint32_t u = (uint32_t)c;",
    "\treturn upper ? map_pair(to_upper_tab, N(to_upper_tab), u) : map_pair(to_lower_tab, N(to_lower_tab), u);",
    "}",
    "",
]
out = os.path.join(os.path.dirname(__file__), "..", "crates", "kiln_runtime", "runtime", "kiln_unicode.c")
with open(out, "w") as f:
    f.write("\n".join(lines))
print("wrote", os.path.normpath(out))
