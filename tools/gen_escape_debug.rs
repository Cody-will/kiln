//! Generates `compiler/src/escape.kn`: the code points that Rust's `{:?}`
//! writes as `\u{..}` (non-printable and grapheme-extending characters), so
//! the self-hosted parser's AST dump escapes strings exactly like
//! `kiln parse --dump`. Run with:
//!
//!     rustc -O -o /tmp/gen_escape_debug tools/gen_escape_debug.rs && /tmp/gen_escape_debug > compiler/src/escape.kn

fn main() {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for u in 0u32..=0x10FFFF {
        let Some(c) = char::from_u32(u) else { continue };
        let s = c.to_string();
        // Same answer for chars, string starts, and string middles.
        let esc = format!("{c:?}").starts_with("'\\u{");
        assert_eq!(esc, format!("{s:?}").starts_with("\"\\u{"));
        assert_eq!(esc, format!("{:?}", format!("a{c}")).starts_with("\"a\\u{"));
        if !esc {
            continue;
        }
        match ranges.last_mut() {
            Some(r) if r.1 + 1 == u || (r.1 == 0xD7FF && u == 0xE000) => r.1 = u,
            _ => ranges.push((u, u)),
        }
    }
    println!("// Generated by tools/gen_escape_debug.rs; do not edit.");
    println!("//");
    println!("// Inclusive ranges of the code points Rust's `{{:?}}` escapes as `\\u{{..}}`.");
    println!();
    println!("static RANGES [u32; {}] = [", ranges.len() * 2);
    for (lo, hi) in &ranges {
        println!("\t{lo:#x}, {hi:#x},");
    }
    println!("]");
    println!();
    println!("// Whether `{{:?}}` writes `c` as `\\u{{..}}`.");
    println!("pub fun escaped(c char) bool {{");
    println!("\tv := c as u32");
    println!("\tlo mut := 0 as usize");
    println!("\thi mut := RANGES.len() / 2");
    println!("\twhile lo < hi {{");
    println!("\t\tmid := (lo + hi) / 2");
    println!("\t\tif v < RANGES[2 * mid] {{");
    println!("\t\t\thi = mid");
    println!("\t\t}} else if v > RANGES[2 * mid + 1] {{");
    println!("\t\t\tlo = mid + 1");
    println!("\t\t}} else {{");
    println!("\t\t\treturn true");
    println!("\t\t}}");
    println!("\t}}");
    println!("\treturn false");
    println!("}}");
}
