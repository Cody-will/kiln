/// Applies a code generation flag (`--release`, `--backend=<name>`);
/// false if `a` is not one.
pub(crate) fn codegen_flag(opts: &mut kiln_codegen::Options, a: &str) -> bool {
    match a {
        "--release" => opts.release = true,
        "--backend=cranelift" => opts.backend = kiln_codegen::Backend::Cranelift,
        "--backend=llvm" => opts.backend = kiln_codegen::Backend::Llvm,
        "--locked" => package::set_locked(),
        _ if selfhost::flag(a) => {}
        _ => return false,
    }
    true
}

/// Picks the default backend: LLVM for `--release` when this `kiln` has it,
/// Cranelift otherwise. `None` for a `--backend` this build lacks.
pub(crate) fn finish_codegen_flags(
    mut opts: kiln_codegen::Options,
    flags: &[String],
) -> Option<kiln_codegen::Options> {
    let explicit = flags.iter().any(|a| a.starts_with("--backend="));
    selfhost::set_explicit_backend(explicit);
    if flags
        .iter()
        .any(|a| a.starts_with("--backend=") && a != "--backend=llvm" && a != "--backend=cranelift")
    {
        return None;
    }
    if !explicit {
        opts.backend = if opts.release && kiln_codegen::llvm_available() {
            kiln_codegen::Backend::Llvm
        } else {
            kiln_codegen::Backend::Cranelift
        };
    }
    if opts.backend == kiln_codegen::Backend::Llvm && !kiln_codegen::llvm_available() {
        eprintln!("error: this `kiln` was built without the LLVM backend (see docs/LLVM.md)");
        return None;
    }
    Some(opts)
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.as_slice() {
        [cmd, flag, file] if cmd == "lex" && flag == "--dump" => {
            let Ok(src) = std::fs::read_to_string(file) else {
                eprintln!("error: cannot read {file}");
                return ExitCode::from(1);
            };
            print!("{}", kiln_lexer::dump::dump(&kiln_lexer::lex(&src)));
            ExitCode::SUCCESS
        }
        [cmd, flag, file] if cmd == "parse" && flag == "--dump" => {
            let Ok(src) = std::fs::read_to_string(file) else {
                eprintln!("error: cannot read {file}");
                return ExitCode::from(1);
            };
            print!("{}", kiln_parser::dump::dump(&src));
            ExitCode::SUCCESS
        }
        [cmd, flag, file] if cmd == "parse" && flag == "--dump-expanded" => {
            let Ok(src) = std::fs::read_to_string(file) else {
                eprintln!("error: cannot read {file}");
                return ExitCode::from(1);
            };
            print!("{}", kiln_parser::dump::dump_expanded(&src));
            ExitCode::SUCCESS
        }
        // The runtime libraries, for linking code from the self-hosted compiler.
        [cmd, flag, dir] if cmd == "runtime" && flag == "--write" => {
            let dir = std::path::Path::new(dir);
            let w = std::fs::create_dir_all(dir)
                .and_then(|_| std::fs::write(dir.join(kiln_runtime::LIB_NAME), kiln_runtime::LIB))
                .and_then(|_| {
                    std::fs::write(dir.join(kiln_runtime::TLS_LIB_NAME), kiln_runtime::TLS_LIB)
                });
            if let Err(e) = w {
                eprintln!("error: cannot write the runtime to {}: {e}", dir.display());
                return ExitCode::from(1);
            }
            ExitCode::SUCCESS
        }
        [cmd, flag, file] if cmd == "borrowck" && flag == "--dump" => {
            let Ok(src) = std::fs::read_to_string(file) else {
                eprintln!("error: cannot read {file}");
                return ExitCode::from(1);
            };
            print!("{}", kiln_borrowck::dump::dump(&src));
            ExitCode::SUCCESS
        }
        [cmd, flag, file] if cmd == "mir" && flag == "--dump" => {
            let Ok(src) = std::fs::read_to_string(file) else {
                eprintln!("error: cannot read {file}");
                return ExitCode::from(1);
            };
            print!("{}", kiln_mir::dump::dump(&src));
            ExitCode::SUCCESS
        }
        [cmd, flag, file] if cmd == "typeck" && flag == "--dump" => {
            let Ok(src) = std::fs::read_to_string(file) else {
                eprintln!("error: cannot read {file}");
                return ExitCode::from(1);
            };
            print!("{}", kiln_typeck::dump::dump(&src));
            ExitCode::SUCCESS
        }
        [cmd, flag, file] if cmd == "resolve" && flag == "--dump" => {
            let Ok(src) = std::fs::read_to_string(file) else {
                eprintln!("error: cannot read {file}");
                return ExitCode::from(1);
            };
            print!("{}", kiln_resolve::dump::dump(&src));
            ExitCode::SUCCESS
        }
        [cmd, flag, file] if cmd == "parse" && flag == "--dump-derive" => {
            let Ok(src) = std::fs::read_to_string(file) else {
                eprintln!("error: cannot read {file}");
                return ExitCode::from(1);
            };
            print!("{}", kiln_parser::dump::dump_derive(&src));
            ExitCode::SUCCESS
        }
        [cmd, file]
            if (cmd == "lex" || cmd == "parse" || cmd == "mir")
                && !std::path::Path::new(file).is_dir() =>
        {
            run(cmd, file)
        }
        [cmd, rest @ ..] if cmd == "check" && rest.len() <= 1 => {
            check(rest.first().map(String::as_str))
        }
        [cmd, rest @ ..] if cmd == "new" => package::new(rest),
        [cmd, rest @ ..] if cmd == "build" => {
            let mut opts = kiln_codegen::Options::default();
            let (mut file, mut out) = (None, None);
            let mut it = rest.iter();
            while let Some(a) = it.next() {
                match a.as_str() {
                    _ if codegen_flag(&mut opts, a) => {}
                    "-o" => out = it.next(),
                    _ if file.is_none() && !a.starts_with('-') => file = Some(a),
                    _ => return usage_error(),
                }
            }
            let Some(opts) = finish_codegen_flags(opts, rest) else {
                return usage_error();
            };
            match rest.iter().any(|a| a == "-o") == out.is_some() {
                true => build(file.map(String::as_str), out, opts),
                false => usage_error(),
            }
        }
        [cmd, rest @ ..] if cmd == "run" => {
            // Options come before the file; everything after it goes to the program.
            let mut opts = kiln_codegen::Options::default();
            let mut i = 0;
            while i < rest.len() && codegen_flag(&mut opts, &rest[i]) {
                i += 1;
            }
            let Some(opts) = finish_codegen_flags(opts, &rest[..i]) else {
                return usage_error();
            };
            // `kiln run [file.kn | dir] [args]`; in a package, `kiln run [-- args]`.
            match rest.get(i) {
                Some(f) if f == "--" => run_program(None, &rest[i + 1..], opts),
                Some(f)
                    if !f.starts_with('-')
                        && (f.ends_with(".kn") || std::path::Path::new(f).is_dir()) =>
                {
                    let args = match rest.get(i + 1) {
                        Some(d) if d == "--" => &rest[i + 2..],
                        _ => &rest[i + 1..],
                    };
                    run_program(Some(f), args, opts)
                }
                None => run_program(None, &[], opts),
                Some(f) if !f.starts_with('-') => run_program(Some(f), &rest[i + 1..], opts),
                _ => usage_error(),
            }
        }
        [cmd, rest @ ..] if cmd == "fmt" => fmt::run(rest),
        [cmd, rest @ ..] if cmd == "lsp" && rest.iter().all(|a| a == "--stdio") => {
            match kiln_lsp::server::run() {
                Ok(()) => ExitCode::SUCCESS,
                Err(e) => {
                    eprintln!("kiln lsp: {e}");
                    ExitCode::from(1)
                }
            }
        }
        [cmd, rest @ ..] if cmd == "test" => match test::parse_args(rest) {
            Some(o) => test::run(o),
            None => usage_error(),
        },
        [flag] if flag == "--version" || flag == "-V" => install::version(false),
        [cmd, rest @ ..] if cmd == "version" && rest.len() <= 1 => {
            install::version(rest.first().is_some_and(|a| a == "-v" || a == "--verbose"))
        }
        [cmd] if cmd == "doctor" => install::doctor(),
        [cmd, rest @ ..] if cmd == "editor" => editor::run(rest),
        [cmd, dir] if cmd == "__install-lib" => install::install_lib(std::path::Path::new(dir)),
        [cmd] if cmd == "help" || cmd == "--help" || cmd == "-h" => {
            println!("{USAGE}");
            ExitCode::SUCCESS
        }
        _ => {
            eprintln!("{USAGE}");
            ExitCode::from(2)
        }
    }
}

fn run(cmd: &str, file: &str) -> ExitCode {
    let src = match std::fs::read_to_string(file) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("error: cannot read `{file}`: {e}");
            return ExitCode::from(2);
        }
    };
    let errors = if cmd == "lex" {
        let lexed = lex(&src);
        let idx = LineIndex::new(&src);
        for t in &lexed.tokens {
            let (line, col) = idx.line_col(t.span.start);
            println!("{line}:{col}\t{}", describe(&t.kind));
        }
        lexed.errors
    } else if cmd == "mir" {
        mir(&src)
    } else {
        let parsed = kiln_parser::parse(&src);
        println!("{:#?}", parsed.file);
        parsed.errors
    };
    report(file, &src, &errors)
}

fn default_output(file: &str) -> std::path::PathBuf {
    let stem = std::path::Path::new(file)
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("a");
    std::path::PathBuf::from(format!("{stem}{}", std::env::consts::EXE_SUFFIX))
}

fn usage_error() -> ExitCode {
    eprintln!("{USAGE}");
    ExitCode::from(2)
}

fn build_to(
    p: &package::Program,
    out: &std::path::Path,
    opts: kiln_codegen::Options,
) -> Result<(), ExitCode> {
    let native = match &p.manifest {
        Some(m) => match kiln_parser::manifest::all_link(m) {
            Ok(n) => n,
            Err(e) => {
                eprintln!("error: {e}");
                return Err(ExitCode::from(2));
            }
        },
        None => Default::default(),
    };
    let has_native =
        !native.libs.is_empty() || !native.c_sources.is_empty() || !native.search.is_empty();
    // kilnc does not resolve `[dependencies]` yet, so packages with
    // dependencies use the built-in compiler (like native `[link]`).
    let has_deps = p
        .manifest
        .as_ref()
        .and_then(|m| kiln_parser::manifest::all_deps(m).ok())
        .is_some_and(|d| !d.is_empty());
    if let Some(kilnc) = selfhost::wanted(selfhost::explicit_backend(), has_native || has_deps) {
        let work = match out
            .parent()
            .filter(|d| d.ends_with("debug") || d.ends_with("release"))
        {
            Some(d) if p.manifest.is_some() => d.join("kilnc"),
            _ => {
                use std::hash::{Hash, Hasher};
                let mut h = std::collections::hash_map::DefaultHasher::new();
                std::fs::canonicalize(&p.root)
                    .unwrap_or(p.root.clone())
                    .hash(&mut h);
                out.hash(&mut h);
                opts.release.hash(&mut h);
                std::env::temp_dir().join(format!("kiln-work-{:016x}", h.finish()))
            }
        };
        match selfhost::build(&kilnc, &p.root, out, &work, opts.release) {
            Ok(()) => return Ok(()),
            Err(msg) => {
                if std::env::var_os("KILN_DEBUG_KILNC").is_some() {
                    eprint!("{msg}");
                }
                // Rust fallback is opt-in: kilnc is the daily driver.
                if std::env::var_os("KILN_ALLOW_RUST_FALLBACK").is_some() {
                    let r = build_to_rust(p, out, opts, &native);
                    if r.is_ok() {
                        eprintln!("note: kilnc failed; built with the deprecated built-in compiler (KILN_ALLOW_RUST_FALLBACK=1; set KILN_DEBUG_KILNC=1 for kilnc's output)");
                    }
                    return r;
                }
                eprint!("{msg}");
                eprintln!("error: kilnc failed (set KILN_DEBUG_KILNC=1 for details; KILN_ALLOW_RUST_FALLBACK=1 to try the deprecated built-in compiler)");
                return Err(ExitCode::from(1));
            }
        }
    }
    build_to_rust(p, out, opts, &native)
}

fn build_to_rust(
    p: &package::Program,
    out: &std::path::Path,
    opts: kiln_codegen::Options,
    native: &kiln_parser::manifest::NativeLink,
) -> Result<(), ExitCode> {
    // Debug info names the root file (spans from 0) by its path.
    let name: &'static str = Box::leak(p.name().into_boxed_str());
    let text: &'static str = Box::leak(p.src().to_string().into_boxed_str());
    kiln_lexer::set_root_source(name, text);
    match kiln_codegen::build_parsed_with(p.pkg.parse.clone(), out, opts, native) {
        Ok(()) => Ok(()),
        Err(kiln_codegen::BuildError::Diagnostics(errs)) => Err(report(&p.name(), p.src(), &errs)),
        Err(kiln_codegen::BuildError::Other(msg)) => {
            eprintln!("error: {msg}");
            Err(ExitCode::from(1))
        }
    }
}

/// `kiln check [file.kn | dir]`.
fn check(target: Option<&str>) -> ExitCode {
    let p = match package::load(target, true) {
        Ok(p) => p,
        Err(c) => return c,
    };
    let errors = kiln_borrowck::check_parse(&p.pkg.parse);
    if errors.is_empty() {
        println!("{}: ok", p.name());
    }
    report(&p.name(), p.src(), &errors)
}

/// Builds a package (skipping the build when its inputs are unchanged) or a
/// single file. Returns the executable's path.
fn build_program(
    p: &package::Program,
    out: Option<&String>,
    opts: kiln_codegen::Options,
) -> Result<(std::path::PathBuf, bool), ExitCode> {
    let out = match (out, &p.manifest) {
        (Some(o), _) => std::path::PathBuf::from(o),
        (None, Some(m)) if p.root.ends_with("src/main.kn") => package::output_path(m, opts.release),
        _ => default_output(&p.name()),
    };
    let stamp = out.with_extension("fingerprint");
    let mut fp = package::fingerprint(p, opts.release, opts.backend == kiln_codegen::Backend::Llvm);
    if selfhost::wanted(selfhost::explicit_backend(), false).is_some() {
        fp.push_str("-kilnc");
    }
    let cached = p.manifest.is_some()
        && out.is_file()
        && std::fs::read_to_string(&stamp).is_ok_and(|s| s == fp);
    if cached {
        return Ok((out, true));
    }
    if let Some(dir) = out.parent().filter(|d| !d.as_os_str().is_empty()) {
        if let Err(e) = std::fs::create_dir_all(dir) {
            eprintln!("error: cannot create {}: {e}", dir.display());
            return Err(ExitCode::from(1));
        }
    }
    build_to(p, &out, opts)?;
    if p.manifest.is_some() {
        let _ = std::fs::write(&stamp, fp);
    }
    Ok((out, false))
}

fn build(target: Option<&str>, out: Option<&String>, opts: kiln_codegen::Options) -> ExitCode {
    let p = match package::load(target, false) {
        Ok(p) => p,
        Err(c) => return c,
    };
    match build_program(&p, out, opts) {
        Ok((out, cached)) => {
            println!(
                "{} {}",
                if cached { "up to date:" } else { "built" },
                out.display()
            );
            ExitCode::SUCCESS
        }
        Err(c) => c,
    }
}

fn run_program(target: Option<&str>, args: &[String], opts: kiln_codegen::Options) -> ExitCode {
    let p = match package::load(target, false) {
        Ok(p) => p,
        Err(c) => return c,
    };
    // Packages build into target/ (and are cached); single files into a
    // temporary directory.
    let tmp = std::env::temp_dir().join(format!("kiln-run-{}", std::process::id()));
    let exe = if p.manifest.is_some() && p.root.ends_with("src/main.kn") {
        match build_program(&p, None, opts) {
            Ok((e, _)) => e,
            Err(c) => return c,
        }
    } else {
        if let Err(e) = std::fs::create_dir_all(&tmp) {
            eprintln!("error: cannot create {}: {e}", tmp.display());
            return ExitCode::from(1);
        }
        let exe = tmp.join(default_output(&p.name()));
        if let Err(c) = build_to(&p, &exe, opts) {
            let _ = std::fs::remove_dir_all(&tmp);
            return c;
        }
        exe
    };
    let exe = if exe.is_relative() && exe.parent().is_some_and(|d| d.as_os_str().is_empty()) {
        std::path::Path::new(".").join(exe)
    } else {
        exe
    };
    let status = std::process::Command::new(&exe).args(args).status();
    let _ = std::fs::remove_dir_all(&tmp);
    match status {
        Ok(s) => match s.code() {
            Some(c) => ExitCode::from(c.clamp(0, 255) as u8),
            None => {
                eprintln!("error: the program was terminated abnormally ({s})");
                ExitCode::from(1)
            }
        },
        Err(e) => {
            eprintln!("error: cannot run {}: {e}", exe.display());
            ExitCode::from(1)
        }
    }
}

fn describe(kind: &TokenKind) -> String {
    match kind {
        TokenKind::Semi { implicit: true } => "Semi (newline)".to_string(),
        other => format!("{other:?}"),
    }
}

pub(crate) fn report(file: &str, src: &str, errors: &[Diagnostic]) -> ExitCode {
    for e in errors {
        eprint!("{}", e.render(file, src));
    }
    if errors.is_empty() {
        ExitCode::SUCCESS
    } else {
        eprintln!(
            "error: {} error{} in `{file}`",
            errors.len(),
            if errors.len() == 1 { "" } else { "s" }
        );
        ExitCode::from(1)
    }
}

fn mir(src: &str) -> Vec<Diagnostic> {
    let parsed = kiln_parser::parse(src);
    if !parsed.errors.is_empty() {
        return parsed.errors;
    }
    let prelude = kiln_resolve::parse_prelude();
    let resolved = kiln_resolve::resolve(&parsed.file, &prelude);
    if !resolved.errors.is_empty() {
        return resolved.errors;
    }
    let mut typed = kiln_typeck::typeck(&resolved);
    if !typed.errors().is_empty() {
        return typed.errors().to_vec();
    }
    for (_, bodies) in kiln_mir::lower_all(&mut typed) {
        for b in bodies {
            println!("{b}");
        }
    }
    vec![]
}
